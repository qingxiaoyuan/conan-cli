func TestDependenciesReadsTextManifest(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "conanfile.txt")
	content := "[requires]\nfmt/10.2.1\n# comment\nzlib/1.3\n\n[generators]\nCMakeDeps\n"
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	dependencies, err := Dependencies(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(dependencies) != 2 || dependencies[0] != "fmt/10.2.1" || dependencies[1] != "zlib/1.3" {
		t.Fatalf("dependencies = %#v", dependencies)
	}
}

func TestAddToEmptyTupleRecipe(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "conanfile.py")
	content := `# Generated by conan-cli
# kind: consume
from conan import ConanFile

class ConanDemoConan(ConanFile):
    name = "conan-demo"
    version = "1.0"
    settings = "os", "compiler", "build_type", "arch"
    requires = ()
    default_options = {}
`
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	deps, err := Dependencies(dir)
	if err != nil || len(deps) != 0 {
		t.Fatalf("empty tuple deps=%#v err=%v", deps, err)
	}
	if _, err := Add(dir, "qtutils/1.0"); err != nil {
		t.Fatal(err)
	}
	data, _ := os.ReadFile(path)
	text := string(data)
	if !strings.Contains(text, `"qtutils/1.0"`) || !strings.Contains(text, "requires = (") {
		t.Fatalf("empty tuple not expanded: %s", text)
	}
	deps, err = Dependencies(dir)
	if err != nil || len(deps) != 1 || deps[0] != "qtutils/1.0" {
		t.Fatalf("deps after add = %#v err=%v", deps, err)
	}
}


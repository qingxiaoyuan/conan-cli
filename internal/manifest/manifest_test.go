func TestEnsureTextCreatesRecipe(t *testing.T) {
	dir := t.TempDir()
	path, created, err := EnsureText(dir, "qmake")
	if err != nil || !created {
		t.Fatalf("created=%v err=%v", created, err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "PkgConfigDeps") {
		t.Fatalf("unexpected generators: %s", data)
	}
}

func TestAddToTextManifest(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "conanfile.txt")
	content := "[requires]\nfmt/10.2.1\n\n[generators]\nCMakeDeps\n"
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := Add(dir, "zlib/1.3"); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	if !strings.Contains(text, "zlib/1.3") {
		t.Fatalf("manifest does not contain dependency: %s", text)
	}
}

